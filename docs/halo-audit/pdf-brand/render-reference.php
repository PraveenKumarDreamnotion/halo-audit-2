<?php
// Reference render of the tm-brand Halo Audit PDF. Sample values copied from the 20 Oct staging PDF.
// Usage (from the repo root): php docs/halo-audit/pdf-brand/render-reference.php SEO-plugin SEO-plugin/assets out.pdf
// The first argument is a folder that has vendor/ (run composer install in SEO-plugin first).
[$_, $engine, $kit, $out] = $argv;
require $engine . '/vendor/autoload.php';
require __DIR__ . '/../../../SEO-plugin/includes/engine/Wp/BrandPdf.php';

use HaloAudit\Wp\BrandPdf as B;

$e = static fn($v): string => htmlspecialchars((string) $v, ENT_QUOTES, 'UTF-8');

$mine = ['url' => 'https://www.zelleducation.com/finance-courses/acca-course/', 'score' => 86, 'grade' => 'B'];
$them = ['url' => 'https://thrivemattic.com', 'score' => 76, 'grade' => 'B'];
$keyword = 'acca course';
$date = '20 October 2026';
$groups = [
    ['On-page for your keyword', 75, 58, 2, 2, 8, 'One main heading'],
    ['Technical', 93, 97, 1, 0, 7, 'Security headers'],
    ['AI readiness', 83, 97, 0, 3, 7, 'AI crawlers can read the page'],
    ['Speed', 100, 50, 0, 0, 3, null],
];
$fixes = [
    ['fail', 'One main heading', 'On-page for your keyword', 'Use exactly one H1 heading on the page. Change any others to H2.'],
    ['fail', 'Keyword in the main heading', 'On-page for your keyword', 'Use your keyword in the H1 heading of the page.'],
    ['fail', 'Security headers', 'Technical', 'Almost no security headers are set. Ask your developer or host to add them.'],
    ['warn', 'AI crawlers can read the page', 'AI readiness', 'Your robots.txt blocks some AI crawlers from this page. Remove those rules if you want AI assistants to cite you.'],
    ['warn', 'Heading order', 'On-page for your keyword', 'Do not skip heading levels. Put an H2 before an H3, and an H3 before an H4.'],
];
$checks = [
    ['One main heading', 'A page needs exactly one H1 so that its main topic is clear.', 'fail', '2 H1 headings', 'pass', '1 H1 heading', 'Use exactly one H1 heading on the page. Change any others to H2.'],
    ['Keyword in the main heading', 'The main heading tells readers and search engines the topic of the page.', 'fail', 'Not found in any H1', 'fail', 'Not found in any H1', 'Use your keyword in the H1 heading of the page.'],
    ['Heading order', 'Headings that go down one level at a time give the page a clear outline.', 'warn', '13 skipped levels', 'warn', '1 skipped level', 'Do not skip heading levels. Put an H2 before an H3, and an H3 before an H4.'],
    ['Image alt text', 'Alt text describes an image to search engines and to people who use screen readers.', 'warn', '254 of 264 images have an alt attribute', 'pass', '19 of 19 images have an alt attribute', 'Add an alt attribute to every image. Use alt="" for images that are decoration only.'],
    ['Title length', 'Search results show about 60 characters of a title.', 'pass', '55 characters', 'warn', '63 characters', ''],
    ['Keyword in the title', 'The title is the strongest on-page signal of what a page is about.', 'pass', 'Found in the title', 'fail', 'Not found in the title', ''],
    ['Meta description', 'The description is often the text shown under your title in search results.', 'pass', '154 characters', 'fail', '181 characters', ''],
];

$assets = $kit;
$mpdf = new \Mpdf\Mpdf(B::config($assets, sys_get_temp_dir() . '/halo-mpdf'));
$mpdf->SetTitle('Halo Audit: SEO comparison report');
$mpdf->SetAuthor('Thrivemattic');
$mpdf->WriteHTML(B::css(), \Mpdf\HTMLParserMode::HEADER_CSS);

$h = B::headerFooter($assets . '/images/logo-dark.png', 'SEO comparison report', 'zelleducation.com · ' . $date,
    'Report generated by thrivemattic.com with Halo Audit');

// ---------- Cover band (inline styles: mPDF does not apply descendant selectors such as `.cover h1`) ----------
$bg = 'background-color:' . B::CHARCOAL . ';';
$k = 'color:#8f9893;font-size:7pt;letter-spacing:1.5pt;font-weight:bold;width:30mm;padding:2pt 0;' . $bg;
$v = 'color:#dfe2df;font-size:8.5pt;padding:2pt 0;' . $bg;
$h .= '<table width="100%" cellpadding="0" cellspacing="0" style="margin-top:-6mm"><tr><td style="' . $bg . 'padding:16pt 18pt">'
    . '<table width="100%" cellpadding="0" cellspacing="0"><tr><td style="' . $bg . '"><img src="' . $e($assets . '/images/logo-white.png') . '" height="7mm" /></td>'
    . '<td align="right" style="' . $bg . 'font-weight:bold;font-size:7pt;letter-spacing:2pt;color:' . B::OLIVE_BRIGHT . '">HALO AUDIT</td></tr></table>'
    . '<div style="font-size:16pt;line-height:1">&nbsp;</div><div style="font-weight:bold;font-size:7pt;letter-spacing:2pt;color:' . B::OLIVE_BRIGHT . '">SEO COMPARISON REPORT</div>'
    . '<div style="font-family:oswald;font-weight:bold;font-size:24pt;line-height:1.15;color:#ffffff">How your page compares for “' . $e($keyword) . '”</div><div style="font-size:8pt;line-height:1">&nbsp;</div>'
    . '<table width="100%" cellpadding="0" cellspacing="0">'
    . '<tr><td style="' . $k . '">YOUR PAGE</td><td style="' . $v . '">' . $e($mine['url']) . '</td></tr>'
    . '<tr><td style="' . $k . '">COMPETITOR</td><td style="' . $v . '">' . $e($them['url']) . '</td></tr>'
    . '<tr><td style="' . $k . '">KEYWORD</td><td style="' . $v . '">' . $e($keyword) . '</td></tr>'
    . '<tr><td style="' . $k . '">DATE</td><td style="' . $v . '">' . $e($date) . '</td></tr>'
    . '</table></td></tr></table>';

// ---------- Score hero ----------
$h .= '<table width="100%" cellpadding="0" style="margin-top:14pt"><tr>'
    . '<td width="34%" valign="bottom"><div class="eyebrow">Your page</div><span class="score">' . $mine['score'] . '</span><span class="outof"> / 100</span> &nbsp;<span class="grade">Grade ' . $mine['grade'] . '</span></td>'
    . '<td width="34%" valign="bottom"><div class="eyebrow" style="color:' . B::TEXT_SECONDARY . '">Competitor</div><span class="score-sm">' . $them['score'] . '</span><span class="outof"> / 100</span> &nbsp;<span class="grade" style="background-color:' . B::TEXT_SECONDARY . '">Grade ' . $them['grade'] . '</span></td>'
    . '<td width="32%" valign="bottom" align="right"><div class="eyebrow" style="color:' . B::TEXT_SECONDARY . '">Difference</div><span class="delta-up">+10 points</span></td>'
    . '</tr></table><div class="rule"></div>';

$h .= '<p>Your page scores 86 out of 100 (grade B). The competitor page scores 76 (grade B). Your page leads on on-page SEO and speed, and trails on technical health and AI readiness. Three checks need fixing and five could be improved. The priority fixes are on page 2.</p>'
    . '<p class="small muted">Grades: A 90 to 100 · B 70 to 89 · C 50 to 69 · D 30 to 49 · F below 30. A check that could not run shows “Not measured” and does not count.</p>';

// ---------- Count tiles ----------
$tiles = [['To fix', 3, 5], ['To improve', 5, 5], ['Passed', 25, 23], ['Not measured', 0, 0]];
$h .= '<table width="100%" cellspacing="6" style="margin:4pt -6pt 0"><tr>';
foreach ($tiles as [$label, $n, $c]) {
    $h .= '<td width="25%" class="tile" style="background-color:' . B::CREAM . ';border-top:2pt solid ' . B::OLIVE . ';padding:8pt">'
        . '<div class="eyebrow" style="color:' . B::TEXT_SECONDARY . '">' . $label . '</div><div class="n" style="font-family:oswaldbold;font-size:22pt;color:' . B::CHARCOAL . '">' . $n . '</div>'
        . '<div class="small muted">Competitor: ' . $c . '</div></td>';
}
$h .= '</tr></table>';

// ---------- Area cards ----------
$h .= '<h2>Scores by area</h2><div class="lede">Halo Audit scores out of 100. Bar: your page in olive, the competitor in grey.</div>';
$h .= '<table width="100%" cellspacing="6" style="margin:2pt -6pt 0">';
foreach (array_chunk($groups, 2) as $pair) {
    $h .= '<tr>';
    foreach ($pair as [$name, $s, $c, $fix, $imp, $pass, $top]) {
        $d = $s - $c;
        $h .= '<td width="50%" style="background-color:' . B::CREAM . ';padding:9pt" valign="top">'
            . '<table width="100%"><tr><td style="background-color:' . B::CREAM . '"><h3>' . $e($name) . '</h3></td><td align="right" style="background-color:' . B::CREAM . '"><span style="font-family:oswaldbold;font-size:18pt;color:' . B::CHARCOAL . '">' . $s . '</span><span class="outof"> / 100</span></td></tr></table>'
            . '<div style="padding-top:6pt"></div>' . B::bar($s) . '<div style="padding-top:2pt"></div>' . B::bar($c, '#b9bcb7', 3.0)
            . '<div class="small muted" style="margin-top:4pt">Competitor ' . $c . ' · ' . ($d >= 0 ? $d . ' ahead' : abs($d) . ' behind') . '</div>'
            . '<div class="small" style="margin-top:3pt">' . $fix . ' to fix · ' . $imp . ' to improve · ' . $pass . ' passed</div>'
            . '<div class="small" style="margin-top:5pt;padding-top:4pt;border-top:0.5pt solid #e2dfd8"><b style="color:' . B::CHARCOAL . '">Top issue:</b> ' . ($top ? $e($top) : 'none, every check passed') . '</div>'
            . '</td>';
    }
    $h .= '</tr>';
}
$h .= '</table>';

// ---------- Page 2: priority fixes ----------
$h .= '<pagebreak /><h2 style="margin-top:0">Priority fixes for your page</h2><div class="lede">5 of 8 shown. Every one is in the findings below.</div><div class="rule"></div>';
$h .= '<table class="list"><tr><th width="6%">#</th><th width="15%">Status</th><th width="32%">Check</th><th>What to do</th></tr>';
foreach ($fixes as $i => [$st, $name, $group, $todo]) {
    $h .= '<tr><td><span style="font-family:oswaldbold;font-size:13pt;color:' . B::CHARCOAL . '">' . ($i + 1) . '</span></td><td>' . B::badge($st) . '</td>'
        . '<td><span class="check">' . $e($name) . '</span><br><span class="why">' . $e($group) . '</span></td><td>' . $e($todo) . '</td></tr>';
}
$h .= '</table>';
$h .= '<p class="small muted" style="margin-top:6pt">' . B::badge('pass') . ' meets the guideline &nbsp; ' . B::badge('warn') . ' partly meets it &nbsp; ' . B::badge('fail') . ' needs action &nbsp; ' . B::badge('not_measured') . ' not tested, so not scored</p>';

// ---------- Findings ----------
$h .= '<h2>On-page for your keyword</h2><div class="lede">Your page 75 / 100 · competitor 58 / 100</div><div class="rule"></div>';
$h .= '<table class="list"><tr><th width="34%">Check</th><th width="33%">Your page</th><th>Competitor</th></tr>';
foreach ($checks as [$name, $why, $ms, $me, $ts, $te, $todo]) {
    $h .= '<tr style="page-break-inside:avoid"><td><span class="check">' . $e($name) . '</span><br><span class="why">' . $e($why) . '</span></td>'
        . '<td>' . B::badge($ms) . '<br>' . $e($me) . '</td><td>' . B::badge($ts) . '<br>' . $e($te) . '</td></tr>';
    if ($todo !== '' && $ms !== 'pass') {
        $h .= '<tr><td colspan="3" style="background-color:' . B::CREAM . ';border-left:2pt solid ' . B::OLIVE . ';padding:5pt 8pt"><b style="color:' . B::CHARCOAL . '">What to do:</b> ' . $e($todo) . '</td></tr>';
    }
}
$h .= '</table>';

$h .= B::cta('thrivemattic.com/contact');

$mpdf->WriteHTML($h, \Mpdf\HTMLParserMode::HTML_BODY);
$mpdf->Output($out, \Mpdf\Output\Destination::FILE);
echo "wrote $out\n";
