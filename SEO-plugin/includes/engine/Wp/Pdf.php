<?php
namespace HaloAudit\Wp;

use HaloAudit\Scorer;
use HaloAudit\Url;

final class Pdf
{
    private const STATUS_LABELS = ['pass' => 'Pass', 'warn' => 'Improve', 'fail' => 'Fix', 'not_measured' => 'Not measured'];
    private const STATUS_COLOURS = ['pass' => '#2e7d32', 'warn' => '#8a5200', 'fail' => '#c62828', 'not_measured' => '#6b6b6b'];

    /** Names the site that made the report, not the plugin's author. Plain text; html() escapes it. */
    public static function defaultFooter(): string
    {
        $title = trim(wp_specialchars_decode((string) get_bloginfo('name'), ENT_QUOTES));
        $home = home_url('/');
        return $title !== ''
            ? sprintf('Report generated by %s (%s) with Halo Audit.', $title, $home)
            : sprintf('Report generated by %s with Halo Audit.', $home);
    }

    public static function filename(array $report): string
    {
        $host = preg_replace('/[^a-z0-9.-]/', '', Url::host($report['url']));
        return 'halo-audit-' . ($host !== '' ? $host : 'report') . '.pdf';
    }

    /** Every dynamic value is escaped. No value from the audited page reaches mPDF as HTML. */
    public static function html(array $report): string
    {
        $e = static fn($value): string => htmlspecialchars((string) $value, ENT_QUOTES, 'UTF-8');
        $summary = $report['summary'];
        $competitor = $report['competitor'] ?? null;

        $out = '<h1>Halo Audit</h1>';
        $out .= '<p><strong>' . ($competitor ? 'Your page' : 'Page') . ':</strong> ' . $e($report['url'])
            . ($competitor ? '<br><strong>Competitor page:</strong> ' . $e($competitor['url']) : '')
            . '<br><strong>Keyword:</strong> ' . $e($report['keyword'])
            . '<br><strong>Date:</strong> ' . $e(gmdate('j F Y', (int) $report['created_at'])) . '</p>';

        if ($competitor) {
            $score = static fn(?array $g): string => $g === null || $g['score'] === null ? 'Not measured' : $e($g['score']);
            $out .= '<h2>Comparison</h2><table class="groups"><tr><th>Area</th><th>Your page</th><th>Competitor page</th></tr>';
            $out .= '<tr><td><strong>Overall</strong></td><td><strong>' . $score(['score' => $summary['overall']]) . '</strong></td><td><strong>'
                . $score(['score' => $competitor['summary']['overall']]) . '</strong></td></tr>';
            foreach ($summary['groups'] as $group => $data) {
                $out .= '<tr><td>' . $e(Scorer::LABELS[$group] ?? $group) . '</td><td>' . $score($data) . '</td><td>'
                    . $score($competitor['summary']['groups'][$group] ?? null) . '</td></tr>';
            }
            $out .= '</table>';
        }

        $out .= $summary['overall'] === null
            ? '<p class="score">Not measured</p>'
            : '<p class="score">' . $e($summary['overall']) . ' / 100 &nbsp; Grade ' . $e($summary['grade']) . '</p>';

        $out .= '<table class="groups"><tr><th>Area</th><th>Score</th><th>Pass</th><th>Improve</th><th>Fix</th></tr>';
        foreach ($summary['groups'] as $group => $data) {
            $out .= '<tr><td>' . $e(Scorer::LABELS[$group] ?? $group) . '</td><td>' . ($data['score'] === null ? 'Not measured' : $e($data['score']))
                . '</td><td>' . $e($data['pass']) . '</td><td>' . $e($data['warn']) . '</td><td>' . $e($data['fail']) . '</td></tr>';
        }
        $out .= '</table>';

        if ($competitor) {
            $out .= self::comparisonFindings($report, $e);
        } else {
            $byGroup = [];
            foreach ($report['checks'] as $row) {
                $byGroup[$row['group']][] = $row;
            }
            foreach ($byGroup as $group => $rows) {
                $out .= '<h2>' . $e(Scorer::LABELS[$group] ?? $group) . '</h2><table class="checks">';
                foreach ($rows as $row) {
                    $colour = self::STATUS_COLOURS[$row['status']] ?? '#6b6b6b';
                    $out .= '<tr><td class="status" style="color:' . $colour . '">' . $e(self::STATUS_LABELS[$row['status']] ?? $row['status']) . '</td><td><strong>'
                        . $e($row['title']) . '</strong><br>' . $e($row['evidence']);
                    if ($row['message'] !== '') {
                        $out .= '<br><em>What to do:</em> ' . $e($row['message']);
                    }
                    $out .= '</td></tr>';
                }
                $out .= '</table>';
            }
        }

        $footer = trim((string) apply_filters('halo_audit_pdf_footer', self::defaultFooter(), $report));
        if ($footer !== '') {
            $out .= '<p class="foot">' . $e($footer) . '</p>';
        }
        return $out;
    }

    /**
     * Comparison findings: one row per check from ReportView::pairs, your page and the competitor page in
     * their own columns. A side where the check did not run says "Not checked".
     */
    private static function comparisonFindings(array $report, callable $e): string
    {
        $mineGroups = $report['summary']['groups'];
        $theirGroups = $report['competitor']['summary']['groups'];
        $score = static fn(?array $g): string => $g === null || $g['score'] === null ? 'Not measured' : $e($g['score']) . ' / 100';
        $cell = static function (?array $side, bool $withFix) use ($e): string {
            if ($side === null) {
                return '<span class="status" style="color:#6b6b6b">Not checked</span>';
            }
            $colour = self::STATUS_COLOURS[$side['status']] ?? '#6b6b6b';
            $out = '<span class="status" style="color:' . $colour . '">' . $e(self::STATUS_LABELS[$side['status']] ?? $side['status']) . '</span><br>' . $e($side['evidence']);
            if ($withFix && ($side['message'] ?? '') !== '') {
                $out .= '<br><em>What to do:</em> ' . $e($side['message']);
            }
            return $out;
        };

        $byGroup = [];
        foreach (\HaloAudit\ReportView::pairs($report['checks'], $report['competitor']['checks']) as $pair) {
            $byGroup[$pair['group']][] = $pair;
        }
        $out = '';
        foreach ($byGroup as $group => $pairs) {
            $out .= '<h2>' . $e(Scorer::LABELS[$group] ?? $group) . '</h2>';
            if (isset($mineGroups[$group]) || isset($theirGroups[$group])) {
                $out .= '<p class="area">Your page: ' . $score($mineGroups[$group] ?? null) . ' &nbsp; Competitor page: ' . $score($theirGroups[$group] ?? null) . '</p>';
            }
            $out .= '<table class="checks"><tr><th>Check</th><th>Your page</th><th>Competitor page</th></tr>';
            foreach ($pairs as $pair) {
                $out .= '<tr><td><strong>' . $e($pair['title']) . '</strong></td><td class="mine">' . $cell($pair['mine'], true) . '</td><td class="theirs">' . $cell($pair['theirs'], false) . '</td></tr>';
            }
            $out .= '</table>';
        }
        return $out;
    }

    public static function render(array $report): string
    {
        $temp = trailingslashit(get_temp_dir()) . 'halo-audit-mpdf';
        wp_mkdir_p($temp);

        $mpdf = new \Mpdf\Mpdf(['tempDir' => $temp, 'format' => 'A4', 'margin_top' => 16, 'margin_bottom' => 16]);
        $mpdf->SetTitle('Halo Audit');
        $mpdf->WriteHTML(self::css(), \Mpdf\HTMLParserMode::HEADER_CSS);
        $mpdf->WriteHTML(self::html($report), \Mpdf\HTMLParserMode::HTML_BODY);
        return $mpdf->Output('', \Mpdf\Output\Destination::STRING_RETURN);
    }

    private static function css(): string
    {
        return 'body{font-family:dejavusans;font-size:10pt;color:#222}'
            . 'h1{font-size:20pt;margin:0 0 6pt}h2{font-size:13pt;margin:14pt 0 4pt;border-bottom:1px solid #ccc}'
            . '.score{font-size:22pt;font-weight:bold;margin:8pt 0}'
            . 'table{width:100%;border-collapse:collapse}td,th{padding:4pt 5pt;border-bottom:1px solid #e5e5e5;vertical-align:top;text-align:left}'
            . '.status{width:70pt;font-weight:bold}.foot{margin-top:18pt;font-size:8pt;color:#666}'
            . '.area{margin:0 0 4pt;color:#444}td.mine,td.theirs{width:38%}';
    }
}
